import {test} from "node:test";
import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {mkdtempSync,mkdirSync,writeFileSync,rmSync} from "node:fs";
import {tmpdir} from "node:os";
import {dirname,join} from "node:path";
import {engineeringSnapshot,engineeringInventoryPlugin,inventoryModuleId,sourceIdentity} from "../../.storybook/engineering-inventory.mjs";

test("engineering snapshot identifies clean and modified source without exposing source contents",t=>{
 const root=mkdtempSync(join(tmpdir(),"v61-engineering-"));
 t.after(()=>rmSync(root,{recursive:true,force:true}));
 const write=(path,source)=>{const file=join(root,path);mkdirSync(dirname(file),{recursive:true});writeFileSync(file,source);};
 const git=(...args)=>execFileSync("git",args,{cwd:root,encoding:"utf8",stdio:["ignore","pipe","pipe"]}).trim();
 git("init","-q");git("config","user.name","Engineering test");git("config","user.email","test@example.invalid");
 write("src/components/ui/button.tsx",'export const Button=()=> <button>private-source-marker</button>;');
 write("src/routes/home.tsx",'import {Button} from "@/components/ui/button"; export const Home=()=> <Button/>;');
 write("src/components/button.stories.tsx",'import {Button} from "./ui/button"; export const Default={render:()=> <Button/>};');
 write("docs/design-coverage/v61-registry.json",JSON.stringify({routes:[{path:"src/routes/home.tsx",layout:"dashboard",stories:["src/components/button.stories.tsx#Default"]}]}));
 git("add",".");git("commit","-qm","initial");
 const commit=git("rev-parse","HEAD");
 const snapshot=engineeringSnapshot(root);
 assert.deepEqual(snapshot.source,{commit,clean:true});
 assert.equal(snapshot.impact.components.find(row=>row.path==="src/components/ui/button.tsx").routeCount,1);
 assert.equal(snapshot.impact.components.find(row=>row.path==="src/components/ui/button.tsx").storyFamilyCount,1);
 assert.ok(!JSON.stringify(snapshot).includes("private-source-marker"));
 assert.ok(!JSON.stringify(snapshot).includes(root.replaceAll("\\","/")));
 const plugin=engineeringInventoryPlugin({projectRoot:root});
 assert.equal(plugin.resolveId("unknown"),null);
 assert.equal(plugin.load("unknown"),null);
 const id=plugin.resolveId(inventoryModuleId);
 assert.equal(id,"\0"+inventoryModuleId);
 const first=plugin.load(id);
 assert.deepEqual(JSON.parse(first.slice("export default ".length,-1)),snapshot);
 write("local-edit.txt","modified");
 assert.equal(sourceIdentity(root).clean,false);
 assert.equal(engineeringSnapshot(root).source.clean,false);
 assert.equal(plugin.load(id),first,"a plugin instance uses one immutable snapshot");
 assert.notEqual(engineeringInventoryPlugin({projectRoot:root}).load(id),first);
});

import {
  boolean,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { createdAt, id, updatedAt } from "./common";
import {
  capacityDemandStatus,
  capacityOfferingStatus,
  capacityReservationStatus,
} from "./enums";
import { people } from "./identity";
import { courseTemplates, sections } from "./academics";
import { jurisdictions, organizations, programs, sites } from "./organizations";

/**
 * What an instructor is capable of teaching. This is deliberately distinct
 * from qualification/compliance claims: capability is the instructional fit,
 * while qualification policy decides whether the person may be assigned.
 */
export const instructorCapabilities = pgTable(
  "instructor_capabilities",
  {
    id: id(),
    personId: uuid("person_id").notNull().references(() => people.id, { onDelete: "restrict" }),
    courseTemplateId: uuid("course_template_id").references(() => courseTemplates.id, { onDelete: "restrict" }),
    subject: text("subject"),
    gradeRange: jsonb("grade_range").$type<{ min?: string; max?: string }>().default({}).notNull(),
    modalities: jsonb("modalities").$type<string[]>().default([]).notNull(),
    active: boolean("active").default(true).notNull(),
    metadata: jsonb("metadata").$type<Record<string, unknown>>().default({}).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index("instructor_capability_person_idx").on(t.personId),
    index("instructor_capability_course_idx").on(t.courseTemplateId),
    index("instructor_capability_subject_idx").on(t.subject),
  ],
);

/** Explicit instructor availability. Weekly recurrence can be described in weeklyPattern. */
export const instructorAvailabilityWindows = pgTable(
  "instructor_availability_windows",
  {
    id: id(),
    personId: uuid("person_id").notNull().references(() => people.id, { onDelete: "restrict" }),
    startsAt: timestamp("starts_at", { withTimezone: true }).notNull(),
    endsAt: timestamp("ends_at", { withTimezone: true }).notNull(),
    timezone: text("timezone").default("America/Los_Angeles").notNull(),
    weeklyPattern: jsonb("weekly_pattern").$type<{
      days?: number[];
      startTime?: string;
      endTime?: string;
    }>(),
    active: boolean("active").default(true).notNull(),
    metadata: jsonb("metadata").$type<Record<string, unknown>>().default({}).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index("instructor_availability_person_idx").on(t.personId, t.startsAt, t.endsAt),
  ],
);

/**
 * Sellable/allocatable teaching capacity. Scope fields are nullable by design:
 * null means the offering is not restricted at that level.
 */
export const instructionalCapacityOfferings = pgTable(
  "instructional_capacity_offerings",
  {
    id: id(),
    personId: uuid("person_id").notNull().references(() => people.id, { onDelete: "restrict" }),
    capabilityId: uuid("capability_id").notNull().references(() => instructorCapabilities.id, { onDelete: "restrict" }),
    availabilityWindowId: uuid("availability_window_id").notNull().references(() => instructorAvailabilityWindows.id, { onDelete: "restrict" }),
    organizationId: uuid("organization_id").references(() => organizations.id, { onDelete: "restrict" }),
    siteId: uuid("site_id").references(() => sites.id, { onDelete: "restrict" }),
    programId: uuid("program_id").references(() => programs.id, { onDelete: "restrict" }),
    jurisdictionId: uuid("jurisdiction_id").references(() => jurisdictions.id, { onDelete: "restrict" }),
    modality: text("modality").notNull(),
    maxSeats: integer("max_seats").notNull(),
    status: capacityOfferingStatus("status").default("open").notNull(),
    metadata: jsonb("metadata").$type<Record<string, unknown>>().default({}).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index("capacity_offering_person_idx").on(t.personId),
    index("capacity_offering_scope_idx").on(t.organizationId, t.siteId, t.programId),
    index("capacity_offering_status_idx").on(t.status),
  ],
);

/** Demand generated by a section. One canonical demand record per section. */
export const sectionCapacityDemands = pgTable(
  "section_capacity_demands",
  {
    id: id(),
    sectionId: uuid("section_id").notNull().references(() => sections.id, { onDelete: "cascade" }),
    expectedSeats: integer("expected_seats").notNull(),
    modality: text("modality").notNull(),
    startsAt: timestamp("starts_at", { withTimezone: true }).notNull(),
    endsAt: timestamp("ends_at", { withTimezone: true }).notNull(),
    status: capacityDemandStatus("status").default("open").notNull(),
    metadata: jsonb("metadata").$type<Record<string, unknown>>().default({}).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    uniqueIndex("section_capacity_demand_section_uq").on(t.sectionId),
    index("section_capacity_demand_status_idx").on(t.status),
  ],
);

/** Seats reserved from an offering for a section's instructional demand. */
export const instructionalCapacityReservations = pgTable(
  "instructional_capacity_reservations",
  {
    id: id(),
    offeringId: uuid("offering_id").notNull().references(() => instructionalCapacityOfferings.id, { onDelete: "restrict" }),
    demandId: uuid("demand_id").notNull().references(() => sectionCapacityDemands.id, { onDelete: "cascade" }),
    sectionId: uuid("section_id").notNull().references(() => sections.id, { onDelete: "cascade" }),
    seats: integer("seats").notNull(),
    status: capacityReservationStatus("status").default("held").notNull(),
    expiresAt: timestamp("expires_at", { withTimezone: true }),
    createdByPersonId: uuid("created_by_person_id").references(() => people.id, { onDelete: "restrict" }),
    metadata: jsonb("metadata").$type<Record<string, unknown>>().default({}).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    uniqueIndex("capacity_reservation_offering_demand_uq").on(t.offeringId, t.demandId),
    index("capacity_reservation_offering_status_idx").on(t.offeringId, t.status),
    index("capacity_reservation_section_idx").on(t.sectionId),
  ],
);
